begin;
create temporary table dmu(a uuid,b uuid,outsider uuid,convo uuid)on commit drop;
insert into dmu select gen_random_uuid(),gen_random_uuid(),gen_random_uuid(),gen_random_uuid();grant select on dmu to authenticated;
insert into auth.users(id,aud,role,email,raw_user_meta_data,raw_app_meta_data,created_at,updated_at)select u,'authenticated','authenticated','qa-'||u||'@example.invalid',jsonb_build_object('display_name','QA_'||substr(replace(u::text,'-',''),1,16)),'{}'::jsonb,now(),now()from dmu cross join lateral unnest(array[a,b,outsider])u;
insert into public.friendships(requester_id,recipient_id,status)select a,b,'accepted' from dmu;
insert into public.conversations(id,user_a,user_b)select convo,least(a,b),greatest(a,b) from dmu;
insert into public.direct_messages(conversation_id,author_id,content,created_at)select convo,a,'oi '||g,now()-interval '1 minute'*g from dmu,generate_series(1,3)g;
set local role authenticated;
do $$declare f record;n int;denied boolean;begin select * into f from dmu;
 perform set_config('request.jwt.claim.sub',f.b::text,true);
 select unread into n from public.dm_unread_counts() where conversation_id=f.convo;if n is distinct from 3 then raise exception'Expected 3 unread, got %',n;end if;
 perform set_config('request.jwt.claim.sub',f.a::text,true);
 if exists(select 1 from public.dm_unread_counts() where conversation_id=f.convo)then raise exception'Own messages counted';end if;
 perform set_config('request.jwt.claim.sub',f.outsider::text,true);
 if exists(select 1 from public.dm_unread_counts())then raise exception'Outsider sees unread';end if;
 denied:=false;begin perform public.mark_conversation_read(f.convo);exception when insufficient_privilege then denied:=true;end;if not denied then raise exception'Outsider marked read';end if;
 perform set_config('request.jwt.claim.sub',f.b::text,true);
 insert into public.social_mutes(user_id,target_id)values(f.b,f.a);
 if exists(select 1 from public.dm_unread_counts())then raise exception'Muted user badged';end if;
 delete from public.social_mutes where target_id=f.a;
 perform public.mark_conversation_read(f.convo);
 if exists(select 1 from public.dm_unread_counts())then raise exception'Read conversation still unread';end if;
 denied:=false;begin insert into public.conversation_reads(user_id,conversation_id)values(f.b,f.convo);exception when insufficient_privilege then denied:=true;end;if not denied then raise exception'Direct write allowed';end if;
end $$;
reset role;
rollback;
