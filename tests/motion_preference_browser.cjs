// Requires Playwright and a local server. Verifica o ajuste "Reduzir animações" com o SO liberado.
const {chromium}=require(process.env.ORBITA_PLAYWRIGHT||'playwright');
const {stub}=require('./fixtures/supabase_fixture.cjs');
const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const tmp=path.resolve(__dirname,'../work/browser-temp');fs.mkdirSync(tmp,{recursive:true});process.env.TEMP=tmp;process.env.TMP=tmp;
let browser;
(async()=>{
 browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||undefined,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference',serviceWorkers:'block'});
 await context.route('**/*',async route=>{
  const url=route.request().url();
  if(url.includes('supabase-js'))return route.fulfill({contentType:'application/javascript',body:stub});
  if(url.endsWith('/api/config'))return route.fulfill({json:{configured:true,supabaseUrl:'https://qa.supabase.co',supabaseKey:'public',callsConfigured:false,storageConfigured:true,pushConfigured:false}});
  return route.continue();
 });
 const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(process.env.ORBITA_TEST_URL||'http://127.0.0.1:8766/',{waitUntil:'domcontentloaded'});
 await page.locator('#message-list .message').first().waitFor();
 await page.evaluate(()=>{const dialog=document.getElementById('app-dialog');if(dialog?.open)dialog.close();});
 assert.equal(await page.locator('body').evaluate(n=>n.dataset.reduceMotion),'false');
 assert.notEqual(await page.locator('#app-view').evaluate(n=>getComputedStyle(n).animationName),'none','sem o ajuste a animação de entrada deve existir');
 const frames=await page.evaluate(async()=>{
  const host=document.createElement('div');
  host.style.cssText='position:fixed;left:8px;top:8px;width:140px;height:90px;opacity:.01;pointer-events:none;z-index:-1';
  document.body.append(host);
  const {mountFx}=await import('/static/fx-engine.js');
  const fx=mountFx(host,{preset:'sparkle',mode:'effect'});
  const canvas=host.querySelector('canvas'),ctx=canvas.getContext('2d');
  let frames=0;const clear=ctx.clearRect.bind(ctx);ctx.clearRect=(...args)=>{frames++;return clear(...args);};
  const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const untilFrames=async target=>{const started=Date.now();while(frames<target&&Date.now()-started<3000)await wait(40);};
  await untilFrames(5);
  const warm=frames;
  await wait(320);const running=frames;
  if(running-warm<3)return {warm,running,stalled:true};
  localStorage.setItem('orbita-reduce-motion','true');window.dispatchEvent(new Event('orbita:motion-changed'));
  const afterToggle=frames;
  await wait(420);const stopped=frames;
  localStorage.removeItem('orbita-reduce-motion');window.dispatchEvent(new Event('orbita:motion-changed'));
  await untilFrames(stopped+5);
  const resumed=frames;
  fx.destroy();host.remove();
  return {warm,running,afterToggle,stopped,resumed};
 });
 assert.ok(frames.running-frames.warm>=3,`motor de partículas não animou: ${JSON.stringify(frames)}`);
 assert.ok(frames.stopped-frames.afterToggle<=1,`motor continuou animando com movimento reduzido: ${JSON.stringify(frames)}`);
 assert.ok(frames.resumed-frames.stopped>=3,`motor não retomou ao desativar o ajuste: ${JSON.stringify(frames)}`);
 await page.evaluate(()=>{localStorage.removeItem('orbita-reduce-motion');window.dispatchEvent(new Event('orbita:motion-changed'));});
 await page.evaluate(()=>document.getElementById('settings').click());
 await page.locator('#app-dialog[open]').waitFor();
 const toggle=page.locator('label.check-field').filter({hasText:'Reduzir animações'}).locator('input');
 await toggle.waitFor({state:'attached'});
 assert.equal(await toggle.count(),1);
 const setToggle=checked=>toggle.evaluate((input,value)=>{input.checked=value;input.dispatchEvent(new Event('change',{bubbles:true}));},checked);
 await setToggle(true);
 assert.equal(await page.locator('body').evaluate(n=>n.dataset.reduceMotion),'true');
 assert.equal(await page.locator('#app-view').evaluate(n=>getComputedStyle(n).animationName),'none');
 assert.equal(await page.locator('#app-dialog[open]').evaluate(n=>getComputedStyle(n).animationName),'none');
 await page.locator('#app-dialog[open] .dialog-header button').click();
 await page.locator('#app-dialog').waitFor({state:'hidden'});
 await page.evaluate(()=>document.getElementById('settings').click());
 const reopened=page.locator('label.check-field').filter({hasText:'Reduzir animações'}).locator('input');
 await reopened.waitFor({state:'attached'});
 await reopened.evaluate(input=>{input.checked=false;input.dispatchEvent(new Event('change',{bubbles:true}));});
 assert.equal(await page.locator('body').evaluate(n=>n.dataset.reduceMotion),'false');
 assert.notEqual(await page.locator('#app-view').evaluate(n=>getComputedStyle(n).animationName),'none');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({settingStopsCss:true,settingStopsFx:true,fxResumes:true,settingOffRestores:true,frames}));
 await context.close();await browser.close();
})().catch(async error=>{console.error(error);await browser?.close();process.exitCode=1;});
