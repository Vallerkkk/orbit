begin;
create temporary table dm_fixture(caller uuid,callee uuid,outsider uuid,convo uuid)on commit drop;
insert into dm_fixture select gen_random_uuid(),gen_random_uuid(),gen_random_uuid(),gen_random_uuid();grant select on dm_fixture to authenticated;
insert into auth.users(id,aud,role,email,raw_user_meta_data,raw_app_meta_data,created_at,updated_at)select u,'authenticated','authenticated','qa-'||u||'@example.invalid',jsonb_build_object('display_name','QA_'||substr(replace(u::text,'-',''),1,16)),'{}'::jsonb,now(),now()from dm_fixture cross join lateral unnest(array[caller,callee,outsider])u;
insert into public.friendships(requester_id,recipient_id,status)select caller,callee,'accepted' from dm_fixture;
insert into public.conversations(id,user_a,user_b)select convo,least(caller,callee),greatest(caller,callee) from dm_fixture;
set local role authenticated;
do $$declare f record;r record;r2 record;denied boolean;n int;begin select * into f from dm_fixture;
 perform set_config('request.jwt.claim.sub',f.caller::text,true);
 select * into r from public.start_dm_call(f.convo,'video');
 if r.existing or (r.event).status<>'ringing' or (r.event).kind<>'video' then raise exception'First start must create a ringing call';end if;
 select * into r2 from public.start_dm_call(f.convo,'voice');
 if not r2.existing or (r2.event).id<>(r.event).id then raise exception'Caller restart duplicated';end if;
 denied:=false;begin insert into public.call_events(conversation_id,caller_id)values(f.convo,f.caller);exception when unique_violation then denied:=true;end;if not denied then raise exception'Second active call inserted';end if;
 perform set_config('request.jwt.claim.sub',f.callee::text,true);
 select * into r2 from public.start_dm_call(f.convo,'voice');
 if not r2.existing or (r2.event).id<>(r.event).id or (r2.event).caller_id<>f.caller then raise exception'Glare: callee start must return the existing call';end if;
 select count(*) into n from public.dm_ringing_calls() d where (d.event).id=(r.event).id;if n<>1 then raise exception'Callee does not see ringing call';end if;
 perform public.call_event_transition((r.event).id,'accepted');
 select * into r2 from public.start_dm_call(f.convo,'voice');
 if not r2.existing or (r2.event).status<>'accepted' then raise exception'Start during active call must return it';end if;
 perform public.call_event_transition((r.event).id,'ended');
 select * into r2 from public.start_dm_call(f.convo,'voice');
 if r2.existing or (r2.event).caller_id<>f.callee then raise exception'New call after end failed';end if;
 perform set_config('request.jwt.claim.sub',f.caller::text,true);
 select count(*) into n from public.dm_ringing_calls();if n<>1 then raise exception'Caller should now see callee ring';end if;
 perform set_config('request.jwt.claim.sub',f.outsider::text,true);
 denied:=false;begin perform public.start_dm_call(f.convo,'voice');exception when insufficient_privilege then denied:=true;end;if not denied then raise exception'Outsider started call';end if;
 select count(*) into n from public.dm_ringing_calls();if n<>0 then raise exception'Outsider sees ring';end if;
end $$;
reset role;
-- Stale ringing row (>35 s) must not block a new call.
update public.call_events set created_at=now()-interval '40 seconds' where conversation_id=(select convo from dm_fixture) and status='ringing';
set local role authenticated;
do $$declare f record;r record;begin select * into f from dm_fixture;
 perform set_config('request.jwt.claim.sub',f.caller::text,true);
 select * into r from public.start_dm_call(f.convo,'voice');
 if r.existing then raise exception'Stale ring blocked new call';end if;
 if not exists(select 1 from public.call_events where conversation_id=f.convo and status='missed') then raise exception'Stale ring not expired';end if;
end $$;
reset role;
rollback;
